def bare(w):
    import unicodedata
    return unicodedata.normalize('NFC',''.join(c for c in unicodedata.normalize('NFD',w) if c!='́'))
def AR(word,ru):
    art,noun=word.split(' ',1)
    if word in EXC: why=EXC[word]
    else:
        b=bare(noun); why=next(f'{d}: {word}.' for e,a,d in END if b.endswith(e))
    tr=[{'a':f'{a} {noun}','why':why} for a in ('ο','η','το') if a!=art]
    tr.append({'a':noun,'why':'Существительное — с артиклем: '+word+'.'})
    return {'ru':f'Артикль: __ {noun} ({ru})','ko':word,'alt':[art],'u':'u1','traps':tr}
