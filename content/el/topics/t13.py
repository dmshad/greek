def X(ru,ko,u,traps=(),alt=()):
    ko=nu(ko)
    tr=[{'a':a,'why':w} for a,w in traps]+[{'a':a,'why':w} for a,w in art_traps(ko,PROF,PWHY)]
    for m in _re.finditer(r'(?:(?<=^)|(?<=[\s(]))(ο|η|το|τα|οι) (\w+) (μου|σου|του|της|μας|σας|τους)\b',ko,_re.I):
        tr.append({'a':ko[:m.start()]+m.group(2)+' '+m.group(3)+ko[m.end():],'why':POSS.format(x=m.group(0))})
    for m in _re.finditer(r'\b(τον|έναν|στον) (\w+)',ko):
        a,w=m.group(1),m.group(2)
        if w in MNOM:   # «τον γιατρός» и «το γιατρό»
            tr.append({'a':ko[:m.start()]+a+' '+MNOM[w]+ko[m.end():],'why':MASC.format(x=m.group(0))})
            if a in ('τον','στον'): tr.append({'a':ko[:m.start()]+a[:-1]+' '+w+ko[m.end():],'why':TO.format(x=m.group(0))})
    for m in _re.finditer(r'\b(στον|στην|στη|στο)\b',ko):
        full={'στον':'σε τον','στην':'σε την','στη':'σε τη','στο':'σε το'}[m.group(1)]
        tr.append({'a':ko[:m.start()]+full+ko[m.end():],'why':STO.format(x=m.group(1))})
    return {'ru':names(ru),'ko':nu(ko),'alt':[nu(a) for a in alt],'u':u,'traps':tr}
def F(nom,ru):
    """Форма: «ο γιατρός (врач)» → «τον γιατρό»."""
    art,w=nom.split(' ',1)
    acc={'ο':'τον','η':'τη(ν)','το':'το','ένας':'έναν','μία':'μία','ένα':'ένα'}[art]
    b=w
    if art in ('ο','ένας'):
        for e,r in (('ος','ο'),('ός','ό'),('ας','α'),('άς','ά'),('ης','η'),('ής','ή'),('ούς','ού')):
            if w.endswith(e): b=w[:-len(e)]+r; break
    ko=f'{acc} {b}'.replace('τη(ν)','[τη|την]')
    tr=[]
    if art=='ο': tr+=[{'a':f'τον {w}','why':MASC.format(x=f'τον {b}')},{'a':f'το {b}','why':TO.format(x=f'τον {b}')},{'a':nom,'why':'Нужен винительный: '+f'τον {b}.'}]
    if art=='ένας': tr+=[{'a':f'έναν {w}','why':MASC.format(x=f'έναν {b}')},{'a':nom,'why':'Нужен винительный: '+f'έναν {b}.'}]
    if art=='η': tr+=[{'a':f'την {w[:-1]}α' if w.endswith('η') else 'x','why':'Женский род не меняется: τη(ν) '+w+'.'}]
    if art=='η': tr+=[{'a':nom,'why':f'Нужен винительный: η → τη(ν), слово не меняется: {nu("τη "+w)}.'}]
    if art=='το': tr+=[{'a':f'τον {w}','why':f'Средний род: το не меняется — το {w}.'}]
    if art=='ένα': tr+=[{'a':f'έναν {w}','why':f'Средний род: ένα не меняется — ένα {w}.'}]
    return {'ru':f'Винительный: {nom} ({ru})','ko':nu(ko),'alt':[],'u':'u1','traps':[t for t in tr if t['a']!='x']}
